"""Fill a survey with synthetic participants through the real HTTP API.

Creates (or reuses) a demo survey whose true preferences differ by group, so you
can check the dashboard shows the expected shifts:

  * Region "South" strongly prefers the spicy items (Jalapeño, Hot honey, Chorizo).
  * Age < 35 likes Pineapple and Hot honey more; 50+ dislikes them.
  * ~3% of participants are "speed clickers" (always left, ~150 ms) and should get flagged.

Usage:
  uv run python scripts/simulate.py --base-url http://localhost:8000 --password secret --participants 300

All simulated participants share your IP, so start the server with a high
RATE_LIMIT_PER_MIN (e.g. 100000) or the per-IP session limit will reject them.
"""

from __future__ import annotations

import argparse
import math
import random
import sys

import httpx

ITEMS = [
    "Pepperoni", "Mushroom", "Margherita", "Pineapple", "Sausage", "Jalapeño", "Hot honey", "Chorizo",
    "Olives", "Anchovies", "Spinach", "Four cheese", "BBQ chicken", "Prosciutto", "Onion", "Bell pepper",
    "Truffle", "Ham", "Artichoke", "Goat cheese", "Bacon", "Feta", "Sun-dried tomato", "Arugula",
]
BASE = {"Pepperoni": 1.6, "Margherita": 1.3, "Mushroom": 0.6, "Sausage": 0.8, "Bacon": 0.9, "Four cheese": 0.7,
        "Anchovies": -1.5, "Olives": -0.4, "Pineapple": -0.3, "Truffle": 0.2, "Artichoke": -0.6}
SPICY = {"Jalapeño", "Hot honey", "Chorizo"}
REGIONS = ["North", "South", "East", "West"]
DIETS = ["No restrictions", "Vegetarian", "Pescatarian"]
MEAT = {"Pepperoni", "Sausage", "Chorizo", "Prosciutto", "Ham", "Bacon", "BBQ chicken"}


def true_theta(label: str, age: int, region: str, diet: str) -> float:
    t = BASE.get(label, 0.0)
    if label in SPICY:
        t += 1.4 if region == "South" else -0.4
    if label in {"Pineapple", "Hot honey"}:
        t += 1.0 if age < 35 else (-0.8 if age >= 50 else 0)
    if diet != "No restrictions" and label in MEAT:
        t -= 3.0
    if diet == "Vegetarian" and label == "Anchovies":
        t -= 2.0
    return t


def setup_survey(c: httpx.Client, slug: str, pairs: int) -> None:
    r = c.post("/admin/surveys", data={"title": "Pizza toppings (simulated)"}, follow_redirects=False)
    sid = int(r.headers["location"].split("/")[3])
    c.post(f"/admin/surveys/{sid}/items/add", data={"lines": "\n".join(ITEMS)})
    c.post(f"/admin/surveys/{sid}/settings", data={
        "title": "Pizza toppings (simulated)", "slug": slug, "prompt": "Which topping would you rather have?",
        "pairs_per_participant": str(pairs), "allow_tie": "on", "allow_skip": "on",
        "intro_md": "Synthetic data generated by `scripts/simulate.py`."})
    for q in [
        {"label": "Age", "type": "number", "bins": "25 35 50 65", "required": "on"},
        {"label": "Region", "type": "choice", "options": "\n".join(REGIONS), "required": "on"},
        {"label": "Diet", "type": "choice", "options": "\n".join(DIETS)},
        {"label": "Favourite pizzeria (optional)", "type": "text"},
    ]:
        c.post(f"/admin/surveys/{sid}/demographics/add", data=q)
    c.post(f"/admin/surveys/{sid}/status", data={"status": "open"})
    print(f"created survey {sid} at /s/{slug}")


def run_participant(base_url: str, slug: str, rng: random.Random, questions: dict[str, int]) -> int:
    age = int(rng.triangular(16, 80, 32))
    region = rng.choices(REGIONS, weights=[3, 3, 2, 2])[0]
    diet = rng.choices(DIETS, weights=[7, 2, 1])[0]
    bot = rng.random() < 0.03
    with httpx.Client(base_url=base_url, follow_redirects=True) as c:
        c.post(f"/s/{slug}/start", data={}).raise_for_status()
        demo = {"Age": str(age), "Region": region, "Diet": diet}
        c.post(f"/s/{slug}/demographics", data={f"q_{qid}": demo.get(label, "") for label, qid in questions.items()}).raise_for_status()
        r = c.get(f"/api/s/{slug}/next")
        r.raise_for_status()
        state = r.json()
        n = 0
        stop_after = rng.randint(5, 40)  # used only when the survey is unlimited
        while "pair" in state:
            p = state["pair"]
            tl = true_theta(p["left"]["label"], age, region, diet)
            tr = true_theta(p["right"]["label"], age, region, diet)
            pl, pr, pt = math.exp(tl), math.exp(tr), 0.25 * math.exp((tl + tr) / 2)
            u = rng.random() * (pl + pr + pt)
            outcome = "left" if u < pl else ("right" if u < pl + pr else "tie")
            if rng.random() < 0.03:
                outcome = "skip"
            if bot:
                outcome, ms = "left", rng.randint(80, 250)
            else:
                ms = int(rng.lognormvariate(7.4, 0.5))
            r = c.post(f"/api/s/{slug}/answer", json={"comparison_id": p["comparison_id"], "outcome": outcome, "response_ms": ms})
            r.raise_for_status()
            state = r.json()
            n += 1
            if state.get("progress", {}).get("target") is None and n >= stop_after:
                c.post(f"/api/s/{slug}/finish")
                break
        return n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default="http://localhost:8000")
    ap.add_argument("--password", required=True, help="admin password (ADMIN_PASSWORD)")
    ap.add_argument("--slug", default="demo")
    ap.add_argument("--participants", type=int, default=300)
    ap.add_argument("--pairs", type=int, default=25, help="pairs per participant when creating the survey")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    with httpx.Client(base_url=args.base_url, follow_redirects=True) as admin:
        r = admin.post("/admin/login", data={"password": args.password, "next": "/admin"})
        if "/login" in str(r.url):
            sys.exit("admin login failed; check --password")
        if admin.get(f"/admin/api/survey-by-slug/{args.slug}").status_code == 404:
            setup_survey(admin, args.slug, args.pairs)
        else:
            print(f"reusing existing survey /s/{args.slug}")
        info = admin.get(f"/admin/api/survey-by-slug/{args.slug}").json()
        if info["status"] != "open":
            sys.exit(f"survey /s/{args.slug} is {info['status']}; open it first")
        qids = {q["label"]: q["id"] for q in info["questions"]}

    rng = random.Random(args.seed)
    total = 0
    for i in range(args.participants):
        total += run_participant(args.base_url, args.slug, rng, qids)
        if (i + 1) % 25 == 0:
            print(f"  {i + 1}/{args.participants} participants, {total} answers")
    print(f"done: {args.participants} participants, {total} answers")


if __name__ == "__main__":
    main()
